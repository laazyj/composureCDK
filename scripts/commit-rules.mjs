/**
 * The rules a commit on `main` must meet, shared by `commits:check` (on a pull
 * request, before merge), `squash:merge` (at merge) and `commits:audit` (on
 * `main`, after). Pure apart from loading nx's commit parser, so `commit-
 * rules.test.mjs` can drive it with plain objects. See docs/ci.md#commits and
 * AGENTS.md#commits-and-pull-requests.  A commit is `{ sha, message,
 * authorEmail, parents }`, where `message` is the full message (subject, blank
 * line, body) and `parents` the parent SHAs.
 */

import { createRequire } from "node:module";

// nx's own code rather than copies of its regexes and lists, so the check reads
// commits exactly as `nx release` will, and follows it across upgrades. Both
// modules ship CommonJS and are reachable through nx's package exports.
const require = createRequire(import.meta.url);
const { parseGitCommit } = require("nx/src/command-line/release/utils/git.js");
const { isAiAgentAuthor } = require("nx/release/changelog-renderer").default.prototype;

/** Whether nx treats an email address as a coding agent's (and so keeps it out of "Thank You"). */
export const isAgentEmail = (email) => isAiAgentAuthor({ email: (email ?? "").trim() });

export const CLAUDE_EMAIL = "noreply@anthropic.com";
export const CLAUDE_CO_AUTHOR = `Co-authored-by: Claude <${CLAUDE_EMAIL}>`;
// A session URL, or `<tool> <version>; model <model> <version>` when there is none.
const SESSION_TRAILER = /^Agent-Session: (https:\/\/\S+|\S.*; model \S.*)$/;
const ANY_SESSION_LINE = /^agent-session:/im;
const LEGACY_SESSION_LINE = /^claude-session:/im;
const CO_AUTHOR_LINE = /^co-authored-by:\s*(?<name>.*?)\s*<(?<email>[^>]+)>\s*$/i;
const TRAILER_LINE = /^[A-Za-z0-9][A-Za-z0-9-]*: \S/;
const AUTOSQUASH_SUBJECT = /^(fixup|squash|amend)! /;

/** A commit as the REST API returns it, in the shape these rules take. */
export const toCommit = (c) => ({
  sha: c.sha,
  message: c.commit.message,
  authorEmail: c.commit.author?.email ?? "",
  parents: c.parents.map((p) => p.sha),
});

/** The subject line of a commit message. */
export const subjectOf = (message) => message.split("\n", 1)[0];

/** Everything after the subject line, with the separating blank line removed. */
export const bodyOf = (message) =>
  message
    .split("\n")
    .slice(1)
    .join("\n")
    .replace(/^\s*\n/, "");

/**
 * The trailers git would read: the lines of the message's last paragraph, if
 * every line in it is a `Key: value` trailer. Stricter than git, which
 * tolerates some non-trailer lines, so a block that passes here always parses.
 */
export function trailersOf(message) {
  const paragraphs = message
    .trim()
    .split(/\n\s*\n/)
    .map((p) => p.trim());
  if (paragraphs.length < 2) return [];
  const lines = paragraphs.at(-1).split("\n");
  return lines.every((line) => TRAILER_LINE.test(line)) ? lines : [];
}

/** The `Co-authored-by` lines in some text, as `{ line, name, email }`. */
export const coAuthorsOf = (lines) =>
  lines.flatMap((line) => {
    const match = CO_AUTHOR_LINE.exec(line.trim());
    return match ? [{ line: line.trim(), ...match.groups }] : [];
  });

/**
 * How a commit shows that a coding agent worked on it, if at all: authored or
 * co-authored from an address nx recognises as an agent's, or naming a
 * session. The last covers an agent nx does not know.
 */
export function agentInvolvement({ message, authorEmail }) {
  const authored = isAgentEmail(authorEmail);
  const coAuthored = coAuthorsOf(message.split("\n")).some((c) => isAgentEmail(c.email));
  const session = ANY_SESSION_LINE.test(message) || LEGACY_SESSION_LINE.test(message);
  return { authored, coAuthored, session, any: authored || coAuthored || session };
}

// Branch prefixes coding agents push to: Claude Code's sessions and the
// Copilot coding agent.
const AGENT_BRANCH = /^(claude|copilot)\//;
// The footer Claude Code (and other agents copying it) puts on a description.
const AGENT_FOOTER = /^\s*🤖 Generated with /m;

/**
 * Why a pull request says an agent wrote it, or `null`. Catches a local
 * session that commits under a person's identity and forgets the trailers,
 * which no commit-level test can see. Returns a phrase that completes
 * "the pull request …".
 */
export function pullRequestAgentSignal({ body, headRef }) {
  if (AGENT_BRANCH.test(headRef ?? "")) return `comes from the agent branch \`${headRef}\``;
  if (AGENT_FOOTER.test(body ?? "")) return "says it was generated by an agent";
  return null;
}

/**
 * Problems with one commit's attribution block. A commit an agent worked on
 * must end with a `Co-authored-by` trailer naming it, with no model or version
 * in the name. One an agent authored, or that names a session, must also carry
 * an `Agent-Session` trailer in that paragraph. A person's commit that credits
 * an assistant may have no session to give. `agentPr` is true when the pull
 * request itself says an agent wrote it: every commit then needs the block.
 */
export function attributionProblems(commit, { agentPr = false } = {}) {
  const involvement = agentInvolvement(commit);
  if (!involvement.any && !agentPr) return [];
  const problems = [];
  const lines = commit.message.split("\n");
  const trailers = trailersOf(commit.message);

  if (lines.some((line) => LEGACY_SESSION_LINE.test(line))) {
    problems.push("uses `Claude-Session:`; write `Agent-Session:`");
  }
  for (const { line, name, email } of coAuthorsOf(lines)) {
    if (email.toLowerCase() === CLAUDE_EMAIL && line !== CLAUDE_CO_AUTHOR) {
      problems.push(`uses \`${line}\`; write exactly \`${CLAUDE_CO_AUTHOR}\``);
    } else if (isAgentEmail(email) && /\d/.test(name)) {
      problems.push(`names a model or version in \`${line}\`; name only the agent`);
    }
  }
  const finalCoAuthors = coAuthorsOf(trailers);
  const credited =
    involvement.authored || involvement.coAuthored
      ? finalCoAuthors.some((c) => isAgentEmail(c.email))
      : finalCoAuthors.length > 0;
  if (!credited) {
    problems.push(
      "does not end with a `Co-authored-by:` trailer for the agent " +
        `(for Claude, \`${CLAUDE_CO_AUTHOR}\`)`,
    );
  }
  if (
    (involvement.authored || involvement.session || agentPr) &&
    !trailers.some((line) => SESSION_TRAILER.test(line))
  ) {
    problems.push(
      "has no `Agent-Session:` trailer in its last paragraph, giving the session URL " +
        "or `<tool> <version>; model <model> <version>`",
    );
  }
  return problems;
}

/**
 * The squash commit GitHub builds from a pull request, with the repository's
 * settings (subject `PR_TITLE`, body `COMMIT_MESSAGES`): one commit's body as
 * it is, or several commits' full messages as a bulleted list.
 */
export function squashMessage(title, number, commits) {
  const subject = `${title} (#${number})`;
  const body =
    commits.length === 1
      ? bodyOf(commits[0].message)
      : commits.map(({ message }) => `* ${message.trim()}`).join("\n\n");
  return { subject, body };
}

/** How nx release reads a commit: its changelog type and whether it is breaking. */
export function nxReading(subject, body) {
  const parsed = parseGitCommit({
    message: subject,
    body,
    shortHash: "0000000",
    author: { name: "", email: "" },
  });
  return { type: parsed.type, breaking: parsed.isBreaking };
}

/**
 * Problems with a pull request before it is squash-merged. `title` is the PR
 * title (checked separately against Conventional Commits), `commits` the
 * branch's commits, oldest first, and `agentSignal` the result of
 * {@link pullRequestAgentSignal}.
 */
export function pullRequestProblems({ title, number, commits, agentSignal = null }) {
  const problems = [];

  if (commits.length > 1) {
    problems.push(
      `The branch has ${commits.length} commits. A pull request is one release-notes entry, ` +
        "so fold them into one commit whose message is the one main should keep " +
        "(`git rebase -i --autosquash`, or `git reset --soft` and recommit), then " +
        "`git push --force-with-lease`. Two entries need two (stacked) pull requests.",
    );
  }
  for (const commit of commits) {
    const short = commit.sha.slice(0, 7);
    const subject = subjectOf(commit.message);
    if (commit.parents.length > 1) {
      problems.push(`${short} is a merge commit ("${subject}"). Rebase onto the base instead.`);
    }
    if (AUTOSQUASH_SUBJECT.test(subject)) {
      problems.push(`${short} is an autosquash commit ("${subject}"). Squash it into its target.`);
    }
    const signalled = agentSignal !== null && !agentInvolvement(commit).any;
    for (const problem of attributionProblems(commit, { agentPr: agentSignal !== null })) {
      const why = signalled ? ` (the pull request ${agentSignal})` : "";
      problems.push(`${short} ("${subject}") ${problem}${why}.`);
    }
  }

  if (commits.length > 0) {
    const titleOnly = nxReading(title, "");
    const { subject, body } = squashMessage(title, number, commits);
    const squashed = nxReading(subject, body);
    if (squashed.type !== titleOnly.type) {
      problems.push(
        `nx would record the squash commit as \`${squashed.type}\`, not the title's ` +
          `\`${titleOnly.type}\`: a commit body quotes \`This reverts commit <sha>.\`. ` +
          "Reword it, or title the pull request as the revert it is.",
      );
    }
    if (squashed.breaking !== titleOnly.breaking) {
      problems.push(
        "nx would record the squash commit as breaking, but the title has no `!`: a commit " +
          "body contains `BREAKING CHANGE:`. Add `!` to the title, or reword the body.",
      );
    }
  }

  return problems;
}

/** The `Agent-Session` lines a commit message names, anywhere in it. */
export const sessionsOf = (message) =>
  message
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => SESSION_TRAILER.test(line));

/**
 * Problems with a commit already on `main`, given the commits of the pull
 * request it was squashed from (empty for a direct push). Looser than
 * {@link attributionProblems} about layout, because GitHub's squash dialog
 * re-appends co-author trailers after a blank line and strands
 * `Agent-Session` in an earlier paragraph; strict about content, because an
 * edit in that dialog is the one change no pull-request check can see.
 * `agentSignal` is {@link pullRequestAgentSignal} for that pull request.
 *
 * Runs alongside {@link squashBodyProblems}, which reports any edit to a
 * merged pull request's body. This one says which attribution an edit lost,
 * and is the only check on a direct push, which has no body to compare.
 */
export function mainCommitProblems(commit, prCommits, agentSignal = null) {
  const all = [commit, ...prCommits];
  const involved = all.map(agentInvolvement);
  if (!involved.some((i) => i.any) && agentSignal === null) return [];
  const problems = [];

  const agentEmails = new Set(
    all.flatMap((c) => [
      ...(isAgentEmail(c.authorEmail) ? [c.authorEmail.toLowerCase()] : []),
      ...coAuthorsOf(c.message.split("\n"))
        .map((a) => a.email.toLowerCase())
        .filter(isAgentEmail),
    ]),
  );
  const finalCoAuthors = coAuthorsOf(trailersOf(commit.message));
  const credits = (email) => finalCoAuthors.some((a) => a.email.toLowerCase() === email);
  const missing = [...agentEmails].filter((email) => !credits(email));
  if (missing.length > 0) {
    problems.push(`has no \`Co-authored-by:\` trailer for ${missing.join(", ")}`);
  } else if (agentEmails.size === 0 && finalCoAuthors.length === 0) {
    problems.push("has no `Co-authored-by:` trailer for the agent");
  }

  const landed = new Set(sessionsOf(commit.message));
  const expected = new Set(prCommits.flatMap((c) => sessionsOf(c.message)));
  const needsSession = agentSignal !== null || involved.some((i) => i.authored || i.session);
  if (needsSession && landed.size === 0 && expected.size === 0) {
    problems.push(
      agentSignal === null
        ? "names no `Agent-Session`, though an agent authored commits in it"
        : `names no \`Agent-Session\`, though its pull request ${agentSignal}`,
    );
  }
  for (const line of expected) {
    if (!landed.has(line)) problems.push(`dropped \`${line}\` from its pull request's commits`);
  }
  return problems;
}

// The keywords GitHub reads as closing an issue, and an issue: `#12`, `o/r#3`.
const CLOSING = String.raw`close[sd]?|fix(?:e[sd])?|resolve[sd]?`;
const ISSUE = String.raw`(?:[\w.-]+\/[\w.-]+)?#\d+`;

/**
 * The issues of `repo` (`owner/name`) a commit message closes: each line that
 * is a closing footer, `Closes #12` or `Fixes: o/r#3, #4`. `Refs` and a
 * keyword mid-sentence close nothing. Sorted, once each. `/squash` closes
 * these itself; see docs/ci.md#merging.
 */
export function closedIssues(message, repo) {
  const numbers = new Set();
  for (const line of message.split("\n")) {
    const footer = CLOSING_FOOTER.exec(line.trim());
    if (!footer) continue;
    for (const [, owner, number] of footer[1].matchAll(/(?:([\w.-]+\/[\w.-]+))?#(\d+)/g)) {
      if (!owner || owner.toLowerCase() === repo.toLowerCase()) numbers.add(Number(number));
    }
  }
  return [...numbers].sort((a, b) => a - b);
}

const CLOSING_FOOTER = new RegExp(
  String.raw`^(?:${CLOSING}):?\s+(${ISSUE}(?:\s*,\s*${ISSUE})*)$`,
  "i",
);

// A footer that links an issue in the release notes: `Closes #12`, `Refs: o/r#3`.
const ISSUE_REFERENCE = new RegExp(String.raw`\b(?:${CLOSING}|refs?)\b:?\s+${ISSUE}`, "i");

/**
 * A body's text and its co-authors, compared apart: the web merge dialog
 * moves every `Co-authored-by` line to the end and adds one for each commit
 * author, so where those lines sit says nothing about what was edited.
 * Trailing whitespace and runs of blank lines are not differences either.
 */
function bodyParts(body) {
  const lines = body.replace(/\r\n?/g, "\n").split("\n");
  const coAuthors = coAuthorsOf(lines);
  const text = lines
    .filter((line) => !CO_AUTHOR_LINE.test(line.trim()))
    .map((line) => line.trimEnd())
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return { text, coAuthors };
}

/**
 * The title a pull request had when it merged: the landed subject without its
 * ` (#N)`, so a title edited afterwards does not count against the commit.
 * Falls back to the pull request's title if the subject has no such suffix.
 */
export function mergedTitle(commit, pr) {
  const subject = subjectOf(commit.message);
  const suffix = ` (#${pr.number})`;
  return subject.endsWith(suffix) ? subject.slice(0, -suffix.length) : pr.title;
}

/**
 * Problems with the body of a commit on `main`, given the pull request it was
 * squashed from (`{ number, title }`) and that PR's commits: whatever differs
 * from the body `/squash` would have written ({@link squashMessage}), whether
 * or not an agent took part. Allows exactly what the web merge dialog does on
 * its own: `Co-authored-by` lines moved to the end, and added for the PR's
 * commit authors, and a lone commit's subject kept as the body's first line. A co-author an agent's address names is left to
 * {@link mainCommitProblems}, so a dropped attribution is reported once.
 */
export function squashBodyProblems(commit, pr, prCommits) {
  if (prCommits.length === 0) return [];
  const expected = bodyParts(squashMessage(mergedTitle(commit, pr), pr.number, prCommits).body);
  const landed = bodyParts(bodyOf(commit.message));
  const problems = [];
  // The dialog's default for one commit whose subject is not the PR title
  // keeps that subject as the body's first line, as 5baf18c (#752) landed.
  const withSubject =
    prCommits.length === 1 && landed.text === bodyParts(prCommits[0].message).text;

  if (landed.text !== expected.text && !withSubject) {
    problems.push(
      landed.text === ""
        ? `landed with an empty body, where its pull request's commit message has one`
        : "landed with a body that differs from its pull request's commit message",
    );
    const kept = new Set(landed.text.split("\n").map((line) => line.trim()));
    for (const line of expected.text.split("\n").map((l) => l.trim())) {
      if (ISSUE_REFERENCE.test(line) && !kept.has(line)) {
        problems.push(`dropped \`${line}\`, so the release notes no longer link the issue`);
      }
    }
  }

  const emails = (list) => new Set(list.map((a) => a.email.toLowerCase()));
  const landedEmails = emails(landed.coAuthors);
  const expectedEmails = emails(expected.coAuthors);
  const authors = new Set(prCommits.map((c) => c.authorEmail.toLowerCase()));
  for (const a of expected.coAuthors) {
    if (!landedEmails.has(a.email.toLowerCase()) && !isAgentEmail(a.email)) {
      problems.push(`dropped \`${a.line}\` from its pull request's commits`);
    }
  }
  for (const a of landed.coAuthors) {
    const email = a.email.toLowerCase();
    if (!expectedEmails.has(email) && !authors.has(email)) {
      problems.push(`added \`${a.line}\`, which no commit in its pull request credits`);
    }
  }
  return problems;
}

// Conclusions a ruleset accepts from a required check.
const PASSING = new Set(["success", "neutral", "skipped"]);

/**
 * Why `/squash` must not merge a pull request, or `[]`: the commenter cannot
 * merge, the pull request is not ready, a check the ruleset requires has not
 * passed on its head, or its commits would not land cleanly
 * ({@link pullRequestProblems}). `permission` is the commenter's repository
 * permission (`admin`, `write`, `read` or `none`), `requiredChecks` the check
 * names the base branch's ruleset requires, and `checkRuns` the head commit's
 * check runs as `{ name, status, conclusion, started_at }`.
 */
export function squashMergeRefusals({
  pr,
  login,
  permission,
  requiredChecks,
  checkRuns,
  commits,
  agentSignal = null,
}) {
  const refusals = [];
  if (permission !== "admin" && permission !== "write") {
    refusals.push(`\`${login}\` has ${permission} access, and only someone who can merge may ask.`);
  }
  if (pr.state !== "open") refusals.push("The pull request is not open.");
  if (pr.draft) refusals.push("The pull request is a draft.");
  if (pr.base.ref !== pr.base.repo.default_branch) {
    refusals.push(
      `The pull request targets \`${pr.base.ref}\`, not \`${pr.base.repo.default_branch}\`. ` +
        "Merge the pull request below it first, then retarget this one.",
    );
  }
  for (const name of requiredChecks) {
    const latest = checkRuns
      .filter((run) => run.name === name)
      .sort((a, b) => (b.started_at ?? "").localeCompare(a.started_at ?? ""))[0];
    // A summary job's check run appears only once the jobs it needs have
    // finished, so no run usually means its workflow is still going.
    if (!latest) {
      refusals.push(
        `The required check **${name}** has not finished on the head commit. It may still be running.`,
      );
    } else if (latest.status !== "completed") {
      refusals.push(`The required check **${name}** is still running.`);
    } else if (!PASSING.has(latest.conclusion)) {
      refusals.push(`The required check **${name}** finished as \`${latest.conclusion}\`.`);
    }
  }
  refusals.push(
    ...pullRequestProblems({ title: pr.title, number: pr.number, commits, agentSignal }),
  );
  return refusals;
}
